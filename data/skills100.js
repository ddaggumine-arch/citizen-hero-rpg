export const SKILLS_100 = [];
Object.entries(RAW_SKILLS).forEach(([slot, list]) => {
  list.forEach((row, idx) => {
    const [name, reqLv, mult, maxPp, mech, customDesc] = row;
    const mInfo = MECH_META[mech] || MECH_META.balanced;
    SKILLS_100.push({
      id: `sk_${slot}_${idx + 1}`,
      slot,
      name,
      reqLv,
      mult,
      maxPp,
      mech,
      mechTag: mInfo.tag,
      desc: `${customDesc} [${mInfo.tag}]`,
    });
  });
});

export function getSkillById(id) {
  return SKILLS_100.find((s) => s.id === id) || null;
}

export function getUnlockedSkillsForLevel(lv = 1) {
  return SKILLS_100.filter((s) => s.reqLv <= lv);
}
