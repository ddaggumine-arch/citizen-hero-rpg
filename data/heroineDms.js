function build50Dms(topics, heroine) {
  const list = [];
  for (let i = 0; i < 50; i++) {
    const base = topics[i % topics.length];
    const suffix = i >= 25 ? (heroine === 'yuki' ? ' (속닥속닥 💕)' : ' (진짜야!! ✨)') : '';
    list.push({
      id: `${heroine}_dm_${i + 1}`,
      prompt: `${base[0]}${suffix}`,
      replies: [
        { label: `💘 "${base[1]}"`, meet: true, love: 8, sp: 15, msg: '설레는 마음으로 한달음에 달려가 직접 만났습니다!' },
        { label: `😊 "${base[2]}"`, meet: false, love: 5, sp: 10, pp: 2, msg: '다정한 답장에 상대방이 하트 스티커를 잔뜩 보냈습니다! (전 기술 PP +2)' },
        { label: `😎 "${base[3]}"`, meet: false, love: 2, sp: 5, msg: '여유롭고 든든한 답장으로 훈훈하게 대화를 마쳤습니다!' },
      ],
    });
  }
  return list;
}

